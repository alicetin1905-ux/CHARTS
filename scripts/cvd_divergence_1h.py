"""The Delta Volume divergence signals with delta from 1H intrabars instead of 1m, on 2H - 1D charts.

Same data, signals, trading rules and costs as scripts/cvd_divergence_backtest.py; only the intrabar timeframe
changes (in the indicator: Auto lower timeframe off, Lower timeframe 1 hour). For each chart the default 1m
intrabars (5m on 1D) are run again side by side. Train / test split as in scripts/cvd_divergence_improve.py.

    python3 scripts/cvd_divergence_1h.py        writes backtests/cvd_divergence_1h.md
"""
import os, sys, time

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cvd_divergence_backtest import EXITS, agg, deltas, groups, load, pct, signals, stats, trade  # noqa: E402
from cvd_divergence_improve import summary  # noqa: E402

OUT = os.path.join('backtests', 'cvd_divergence_1h.md')
TFS = [('2H', 120, 1), ('4H', 240, 1), ('6H', 360, 1), ('8H', 480, 1), ('12H', 720, 1), ('1D', 1440, 5)]


def main():
    m = load()
    span = f"{time.strftime('%Y-%m-%d', time.gmtime(m['t'][0] / 1000))} – {time.strftime('%Y-%m-%d', time.gmtime(m['t'][-1] / 1000))}"
    rows = []
    for tf, minutes, default_ib in TFS:
        starts = groups(m['t'], minutes)
        bars = agg(m, starts)
        for ib in (60, default_ib):
            sigs, _ = signals(bars, deltas(m, bars, starts, ib)['intrabar'])
            for ex in EXITS:
                tr = trade(m, starts, sigs, ex)
                rows.append((tf, ib, ex, stats(m, tr), summary(m, [x[:5] for x in tr])))
                s = rows[-1][3]
                print(f'{tf:>4} {ib:>3}m {ex:>7}  trades {s["n"]:4d}  PF {s["pf"]:.2f}  net {s["net"]:+.0%}  '
                      f'mdd {s["mdd"]:.0%}', flush=True)
    write(rows, span, m['c'][-1] / m['o'][0] - 1)


def write(rows, span, hold):
    years = sorted(rows[0][3]['years'])
    L = ['# Delta Volume divergence signals with delta from 1H intrabars', '',
         f'Generated by `scripts/cvd_divergence_1h.py`. Binance USDⓈ-M BTCUSDT 1m candles, **{span}**. Same signals, '
         'entries, stops and costs as [`cvd_divergence.md`](cvd_divergence.md); delta is built from **1H** intrabars '
         '(indicator settings: Auto lower timeframe off, Lower timeframe 1 hour), next to the default 1m intrabars '
         '(5m on 1D). Train Oct 2020 – Dec 2023, test Jan 2024 – Sep 2026: PF and net from the closed trades in each '
         'period.', '',
         '- Entry at the next bar\'s open, 1×, full equity, 0.075 % cost per side. Stop at the divergence pivot, '
         'checked on 1m candles. An opposite signal closes and reverses. **reverse**: no target. **2R**: take profit '
         'at twice the stop distance.',
         f'- Buy & hold over the same period: **{pct(hold)}**.', '',
         '## Results', '',
         '| Chart | Intrabars | Exit | Trades / yr | Win % | Profit factor | Net return | CAGR | Max DD | PF long | '
         'PF short | Train PF | Test PF |',
         '|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    for tf, ib, ex, s, tt in rows:
        L.append(f'| {tf} | {"1H" if ib == 60 else f"{ib}m"} | {ex} | {s["per_year"]:.0f} | {s["win"]:.0%} | '
                 f'{s["pf"]:.2f} | {pct(s["net"])} | {s["cagr"]:+.1%} | {s["mdd"]:.0%} | {s["pf_long"]:.2f} | '
                 f'{s["pf_short"]:.2f} | {tt["train"]["pf"]:.2f} ({tt["train"]["n"]}) | '
                 f'{tt["test"]["pf"]:.2f} ({tt["test"]["n"]}) |')
    L += ['', 'Train / test: profit factor (trades).', '',
          '## By calendar year (1H intrabars)', '',
          '| Chart | Exit | ' + ' | '.join(str(y) for y in years) + ' |', '|---|---|' + '---|' * len(years)]
    for tf, ib, ex, s, _ in rows:
        if ib == 60:
            L.append(f'| {tf} | {ex} | ' + ' | '.join(pct(s['years'][y]) for y in years) + ' |')
    L += ['', f'{years[0]} starts in October, {years[-1]} ends in September.']
    open(OUT, 'w').write('\n'.join(L) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
