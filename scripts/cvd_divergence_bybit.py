"""Does the 1H-intrabar CVD divergence result hold on Bybit? Same rules on Bybit BTCUSDT.P.

Bybit candles come from scripts/bybit_data.py (data/bybit_15m.json, 15m), so here stops and targets are checked on
15m candles (stop first when both are inside one candle) and delta is built from 1H intrabars made of them.
Binance is run again the same way (its 1m candles resampled to 15m), so the two exchanges are compared on equal
terms; the 1m Binance numbers from scripts/cvd_divergence_1h.py are listed too.
Same signals, entries, costs, period (Oct 2020 - Sep 2026) and train / test split as the other CVD scripts.

    python3 scripts/bybit_data.py                  first, once (downloads data/bybit_15m.json)
    python3 scripts/cvd_divergence_bybit.py        writes backtests/cvd_divergence_bybit.md
"""
import calendar, json, os, sys, time

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from cvd_divergence_backtest import EXITS, agg, deltas, groups, load, pct, signals, stats, trade  # noqa: E402
from cvd_divergence_improve import summary  # noqa: E402

OUT = os.path.join('backtests', 'cvd_divergence_bybit.md')
BYBIT = os.path.join('data', 'bybit_15m.json')
START = calendar.timegm((2020, 10, 1, 0, 0, 0)) * 1000
END = calendar.timegm((2026, 10, 1, 0, 0, 0)) * 1000
TFS = [('2H', 120), ('4H', 240), ('6H', 360)]


def bybit():
    a = np.array(json.load(open(BYBIT)), dtype=np.float64)
    a = a[(a[:, 0] >= START) & (a[:, 0] < END)]
    return dict(t=a[:, 0].astype(np.int64), o=a[:, 1], h=a[:, 2], l=a[:, 3], c=a[:, 4], v=a[:, 5], tb=np.zeros(len(a)))


def run(m, label):
    """m: candles of any base resolution (stops are checked on them). Delta from 1H intrabars."""
    rows = []
    for tf, minutes in TFS:
        starts = groups(m['t'], minutes)
        bars = agg(m, starts)
        sigs, _ = signals(bars, deltas(m, bars, starts, 60)['intrabar'])
        for ex in EXITS:
            tr = trade(m, starts, sigs, ex)
            rows.append((label, tf, ex, stats(m, tr), summary(m, [x[:5] for x in tr])))
            s = rows[-1][3]
            print(f'{label:>16} {tf:>3} {ex:>7}  trades {s["n"]:4d}  PF {s["pf"]:.2f}  net {s["net"]:+.0%}  '
                  f'mdd {s["mdd"]:.0%}', flush=True)
    return rows


def main():
    b = bybit()
    m1 = load()
    m15 = agg(m1, groups(m1['t'], 15))
    span = f"{time.strftime('%Y-%m-%d', time.gmtime(b['t'][0] / 1000))} – {time.strftime('%Y-%m-%d', time.gmtime(b['t'][-1] / 1000))}"
    gaps = int((np.diff(b['t']) != 900_000).sum())
    rows = run(b, 'Bybit 15m') + run(m15, 'Binance 15m') + run(m1, 'Binance 1m')
    hold = {'Bybit': b['c'][-1] / b['o'][0] - 1, 'Binance': m1['c'][-1] / m1['o'][0] - 1}
    write(rows, span, gaps, hold)


def write(rows, span, gaps, hold):
    years = sorted(rows[0][3]['years'])
    L = ['# CVD divergence signals (1H intrabars): Bybit vs Binance', '',
         f'Generated by `scripts/cvd_divergence_bybit.py`. Bybit BTCUSDT perpetual 15m candles **{span}** '
         f'({gaps} gaps in the 15m series), Binance USDⓈ-M BTCUSDT 1m candles over the same period. Same signals, '
         'entries, stops and costs as [`cvd_divergence_1h.md`](cvd_divergence_1h.md): delta from 1H intrabars, '
         'entry at the next open, stop at the divergence pivot, opposite signal reverses, 1×, 0.075 % per side.', '',
         '- **Bybit 15m** and **Binance 15m**: stops and targets checked on 15m candles (stop first if both are in '
         'one candle). **Binance 1m**: checked on 1m candles, as in the other reports.',
         f'- Buy & hold: Bybit {pct(hold["Bybit"])}, Binance {pct(hold["Binance"])}.',
         '- Train Oct 2020 – Dec 2023, test Jan 2024 – Sep 2026: profit factor (trades) of the closed trades in each.', '',
         '## Results', '',
         '| Data | Chart | Exit | Trades / yr | Win % | Profit factor | Net return | CAGR | Max DD | PF long | PF short | Train PF | Test PF |',
         '|---|---|---|---|---|---|---|---|---|---|---|---|---|']
    for label, tf, ex, s, tt in rows:
        L.append(f'| {label} | {tf} | {ex} | {s["per_year"]:.0f} | {s["win"]:.0%} | {s["pf"]:.2f} | {pct(s["net"])} | '
                 f'{s["cagr"]:+.1%} | {s["mdd"]:.0%} | {s["pf_long"]:.2f} | {s["pf_short"]:.2f} | '
                 f'{tt["train"]["pf"]:.2f} ({tt["train"]["n"]}) | {tt["test"]["pf"]:.2f} ({tt["test"]["n"]}) |')
    L += ['', '## By calendar year', '',
          '| Data | Chart | Exit | ' + ' | '.join(str(y) for y in years) + ' |', '|---|---|---|' + '---|' * len(years)]
    for label, tf, ex, s, _ in rows:
        L.append(f'| {label} | {tf} | {ex} | ' + ' | '.join(pct(s['years'].get(y, 0)) for y in years) + ' |')
    L += ['', f'{years[0]} starts in October, {years[-1]} ends in September.']
    open(OUT, 'w').write('\n'.join(L) + '\n')
    print('wrote', OUT)


if __name__ == '__main__':
    main()
